//! Build script: tải filter list và embed vào binary qua include_str!.
//!
//! Danh sách được cache trong `$OUT_DIR/kestrel_filters/` giữa các build, nên
//! chỉ tải lần đầu. Dùng env vars để điều khiển:
//!
//! - `KESTREL_REQUIRE_FILTERS=1` — build fail nếu tải thất bại (dùng cho release).
//! - `KESTREL_REFRESH_FILTERS=1` — buộc tải lại dù đã có cache.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};

/// (const_name, filename, url)
const FILTERS: &[(&str, &str, &str)] = &[
    (
        "EASYLIST",
        "easylist.txt",
        "https://easylist.to/easylist/easylist.txt",
    ),
    (
        "EASYPRIVACY",
        "easyprivacy.txt",
        "https://easylist.to/easylist/easyprivacy.txt",
    ),
    (
        "FANBOY_ANNOYANCES",
        "fanboy-annoyances.txt",
        "https://secure.fanboy.co.nz/fanboy-annoyance.txt",
    ),
];

const MIN_VALID_SIZE: u64 = 1024;

fn main() {
    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR missing"));
    let filters_dir = out_dir.join("kestrel_filters");
    fs::create_dir_all(&filters_dir).expect("create kestrel_filters dir");

    let required = env::var("KESTREL_REQUIRE_FILTERS").as_deref() == Ok("1");
    let refresh = env::var("KESTREL_REFRESH_FILTERS").as_deref() == Ok("1");

    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-env-changed=KESTREL_REQUIRE_FILTERS");
    println!("cargo:rerun-if-env-changed=KESTREL_REFRESH_FILTERS");

    let mut code = String::new();
    code.push_str("// Generated by build.rs — do not edit.\n\n");

    for (const_name, filename, url) in FILTERS {
        let path = filters_dir.join(filename);
        let need_download = refresh || !path.exists();

        if need_download {
            println!("cargo:warning=kestrel: downloading {filename}");
            download_to(url, &path, required);
        } else {
            println!("cargo:warning=kestrel: using cached {filename}");
        }

        if required {
            match fs::metadata(&path) {
                Ok(m) if m.len() >= MIN_VALID_SIZE => {}
                Ok(m) => panic!(
                    "filter {filename} too small ({} bytes); release requires valid filters",
                    m.len()
                ),
                Err(e) => panic!("filter {filename} missing after download: {e}"),
            }
        }

        code.push_str(&format!(
            "pub const {const_name}: &str = include_str!({path:?});\n",
            const_name = const_name,
            path = path.display().to_string(),
        ));
    }

    code.push_str(
        r#"
/// Rules cho level 1 (Standard): EasyList + EasyPrivacy.
pub fn rules_standard() -> Vec<String> {
    let mut v: Vec<String> = EASYLIST.lines().map(String::from).collect();
    v.extend(EASYPRIVACY.lines().map(String::from));
    v
}

/// Rules cho level 2 (Aggressive): Standard + Fanboy's Annoyances.
pub fn rules_aggressive() -> Vec<String> {
    let mut v = rules_standard();
    v.extend(FANBOY_ANNOYANCES.lines().map(String::from));
    v
}

/// Trả về rules theo level (0/1/2). Level 0 trả về rỗng.
pub fn rules_for_level(level: u8) -> Vec<String> {
    match level {
        1 => rules_standard(),
        2 => rules_aggressive(),
        _ => Vec::new(),
    }
}
"#,
    );

    let out_path = out_dir.join("kestrel_filters.rs");
    fs::write(&out_path, code).expect("write kestrel_filters.rs");
}

fn download_to(url: &str, path: &Path, required: bool) {
    let result = ureq::get(url).call().and_then(|r| r.into_string());

    match result {
        Ok(text) if text.len() as u64 >= MIN_VALID_SIZE => {
            if let Err(e) = fs::write(path, text) {
                println!("cargo:warning=kestrel: write {path:?} failed: {e}");
                if required {
                    panic!("failed to write filter: {e}");
                }
                let _ = fs::write(path, "");
            }
        }
        Ok(text) => {
            println!(
                "cargo:warning=kestrel: {url} returned suspiciously small response ({} bytes)",
                text.len()
            );
            if required {
                panic!("filter response too small from {url}");
            }
            let _ = fs::write(path, "");
        }
        Err(e) => {
            println!("cargo:warning=kestrel: download {url} failed: {e}");
            if required {
                panic!("required filter download failed: {e}");
            }
            let _ = fs::write(path, "");
        }
    }
}
